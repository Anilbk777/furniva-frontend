export function bsMonthLength(year: number, month: number): number {
  const months = BS_MONTH_DAYS[year]
  if (!months || month < 1 || month > 12) return 0
  return months[month - 1] ?? 0
}

export function bsYearLength(year: number): number {
  const months = BS_MONTH_DAYS[year]
  if (!months) return 0
  return months.reduce((total, days) => total + days, 0)
}

export function isLeapBsYear(year: number): boolean {
  return bsYearLength(year) === 366
}

export function parseBsDate(value: string): BsDate | null {
  if (!value) return null

  const match = /^(\d{4})-(\d{1,2})-(\d{1,2})$/.exec(toAsciiDigits(value.trim()))
  if (!match) return null

  const [, yearPart, monthPart, dayPart] = match
  if (!yearPart || !monthPart || !dayPart) return null

  const year = Number(yearPart)
  const month = Number(monthPart)
  const day = Number(dayPart)
  if (year < MIN_BS_YEAR || year > MAX_BS_YEAR) return null
  if (day < 1 || day > bsMonthLength(year, month)) return null

  return { year, month, day }
}

export function formatBsDate(date: BsDate): string {
  const month = String(date.month).padStart(2, '0')
  const day = String(date.day).padStart(2, '0')
  return `${date.year}-${month}-${day}`
}

export function shiftBsMonth(year: number, month: number, delta: number): {
  year: number
  month: number
} {
  const minIndex = MIN_BS_YEAR * 12
  const maxIndex = MAX_BS_YEAR * 12 + 11
  const index = Math.min(
    maxIndex,
    Math.max(minIndex, year * 12 + (month - 1) + delta),
  )
  return { year: Math.floor(index / 12), month: (index % 12) + 1 }
}

/** Weekday index (0 = Sunday) of the first day of a BS month. */
export function bsFirstWeekday(year: number, month: number): number {
  let offset = 0
  for (let y = MIN_BS_YEAR; y < year; y += 1) offset += bsYearLength(y)
  for (let m = 1; m < month; m += 1) offset += bsMonthLength(year, m)
  return (3 + offset) % 7
}

export function adToBs(date: Date = new Date()): BsDate {
  const start = Date.UTC(1943, 3, 14)
  const target = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate())
  let days = Math.round((target - start) / 86_400_000)
  if (days < 0) days = 0

  let year = MIN_BS_YEAR
  let month = 1
  while (year <= MAX_BS_YEAR) {
    const length = bsMonthLength(year, month)
    if (days < length) return { year, month, day: days + 1 }
    days -= length
    month += 1
    if (month > 12) {
      month = 1
      year += 1
    }
  }

  return { year: MAX_BS_YEAR, month: 12, day: bsMonthLength(MAX_BS_YEAR, 12) }
}

export function todayBs(): BsDate {
  return adToBs()
}

export function todayBsString(): string {
  return formatBsDate(adToBs())
}

export function isSameBsDate(a: BsDate | null, b: BsDate | null): boolean {
  return Boolean(a && b && a.year === b.year && a.month === b.month && a.day === b.day)
}
